/* ---------- Language state ---------- */

const Lang = {
  memory: null,
  detect() {
    const nav = (navigator.language || "en").toLowerCase();
    if (nav.startsWith("fr")) return "fr";
    if (nav.startsWith("ja")) return "ja";
    return "en";
  },
  get() {
    try {
      const s = localStorage.getItem("kuma-lang");
      if (s && I18N[s]) return s;
    } catch (e) { if (this.memory) return this.memory; }
    return this.memory || this.detect();
  },
  set(lang) {
    if (!I18N[lang]) return;
    this.memory = lang;
    try { localStorage.setItem("kuma-lang", lang); } catch (e) { /* in-memory only */ }
    applyI18n();
    window.dispatchEvent(new Event("kuma:lang"));
  },
};

function t(key) {
  const lang = Lang.get();
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

function tf(key, vars) {
  let s = t(key);
  for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
  return s;
}

/* ---------- Apply translations to the page ---------- */

function applyI18n() {
  const lang = Lang.get();
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-ph"));
  });

  document.querySelectorAll(".lang-switch button").forEach((b) => {
    b.classList.toggle("is-active", b.getAttribute("data-lang") === lang);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-switch button").forEach((b) => {
    b.addEventListener("click", () => Lang.set(b.getAttribute("data-lang")));
  });
  applyI18n();
});
